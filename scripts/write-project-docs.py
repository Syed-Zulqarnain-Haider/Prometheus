def docstring_line(path: Path) -> str:
    """First line of a module docstring - the one-line 'what is this'."""
    try:
        doc = ast.get_docstring(ast.parse(path.read_text()))
    except (SyntaxError, UnicodeDecodeError):
        return ""
    return doc.strip().splitlines()[0].strip() if doc else ""


def route_for(page: Path) -> str:
    """URL for an App Router page.tsx, with (group) segments removed."""
    parts = page.relative_to(Path("frontend/app")).parts[:-1]
    kept = [p for p in parts if not (p.startswith("(") and p.endswith(")"))]
    return "/" + "/".join(kept) if kept else "/"


def pages_section() -> str:
    found = sorted(Path("frontend/app").rglob("page.tsx"), key=route_for)
    rows = ["| Route | File |", "|---|---|"]
    rows += [f"| `{route_for(p)}` | `{p.as_posix()}` |" for p in found]
    return "\n".join(rows)


def endpoints_for(module: Path) -> tuple[str, list[str]]:
    """(router prefix, ["GET /path", ...]) declared in one api module."""
    tree = ast.parse(module.read_text())
    prefix = ""
    routes: list[str] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and getattr(node.func, "id", "") == "APIRouter":
            for kw in node.keywords:
                if kw.arg == "prefix" and isinstance(kw.value, ast.Constant):
                    prefix = str(kw.value.value)
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            for dec in node.decorator_list:
                if not isinstance(dec, ast.Call):
                    continue
                attr = dec.func
                if not isinstance(attr, ast.Attribute):
                    continue
                if attr.attr not in {"get", "post", "put", "patch", "delete"}:
                    continue
                if not (dec.args and isinstance(dec.args[0], ast.Constant)):
                    continue
                routes.append(f"{attr.attr.upper()} {dec.args[0].value}")
    return prefix, routes


def endpoints_section() -> tuple[str, int]:
    base = Path("backend/app/api/v1")
    lines = ["Mounted under `/api/v1`. Every route verifies the token and resolves scopes.", ""]
    total = 0
    for module in sorted(base.glob("*.py")):
        if module.name == "__init__.py":
            continue
        prefix, routes = endpoints_for(module)
        if not routes:
            continue
        total += len(routes)
        summary = docstring_line(module)
        head = f"**`{module.name}`**"
        if summary:
            head += f" - {summary}"
        lines.append(head)
        for route in routes:
            method, path = route.split(" ", 1)
            full = (prefix + path).rstrip("/") or prefix or path
            lines.append(f"- `{method:6s} /api/v1{full}`")
        lines.append("")
    return "\n".join(lines).rstrip(), total


def modules_section(folder: str) -> tuple[str, int]:
    base = Path(folder)
    rows = ["| Module | What it does |", "|---|---|"]
    count = 0
    for module in sorted(base.glob("*.py")):
        if module.name == "__init__.py":
            continue
        count += 1
        rows.append(f"| `{module.name}` | {docstring_line(module) or '-'} |")
    return "\n".join(rows), count


def models_section() -> tuple[str, int]:
    base = Path("backend/app/models")
    rows = ["| Module | Tables |", "|---|---|"]
    tables = 0
    for module in sorted(base.glob("*.py")):
        if module.name in {"__init__.py", "base.py"}:
            continue
        names = []
        for node in ast.walk(ast.parse(module.read_text())):
            if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "__tablename__" for t in node.targets
            ):
                if isinstance(node.value, ast.Constant):
                    names.append(str(node.value.value))
        tables += len(names)
        rows.append(f"| `{module.name}` | {', '.join(f'`{n}`' for n in names) or '-'} |")
    return "\n".join(rows), tables


def frontend_section() -> str:
    rows = ["| Component group | Files |", "|---|---|"]
    base = Path("frontend/components")
