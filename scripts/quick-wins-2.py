# A guarded replacement prints the file it found so it can be re-anchored without a
# second round-trip. Cap it so a surprise never floods the terminal.
MAX_ECHO_LINES = 400


def main() -> int:
    if not Path("frontend/app").is_dir():
        print("ABORTED: run this from the repository root")
        return 1

    data = json.loads(base64.b64decode(PAYLOAD.strip()).decode())
    problems: list[str] = []
    echoes: list[str] = []
    planned: dict[str, str] = {}
    skipped: list[str] = []

    for rel, content in data["new_files"].items():
        path = Path(rel)
        if path.exists() and path.read_text() == content:
            skipped.append(f"{rel}: already present and identical")
            continue
        planned[rel] = content

    for item in data.get("replacements", []):
        rel = item["path"]
        path = Path(rel)
        if not path.exists():
            problems.append(f"  {rel}: file not found")
            continue
        current = path.read_text()
        if current == item["content"]:
            skipped.append(f"{rel}: already replaced")
            continue
        actual = hashlib.sha256(current.encode()).hexdigest()
        if actual != item["expect_sha256"]:
            problems.append(
                f"  {rel}: this file is not the one the replacement was written against.\n"
                f"        expected sha256 {item['expect_sha256'][:16]}…\n"
                f"        found            {actual[:16]}…\n"
                f"        Its current contents are printed below so it can be re-done."
            )
            lines = current.splitlines()
            body = lines[:MAX_ECHO_LINES]
            echoes.append(
                f"───── {rel} ({len(lines)} lines) ─────\n"
                + "\n".join(body)
                + ("\n… truncated …" if len(lines) > MAX_ECHO_LINES else "")
            )
            continue
        planned[rel] = item["content"]

    for index, item in enumerate(data["edits"], start=1):
        rel = item["path"]
        path = Path(rel)
        if not path.exists():
            problems.append(f"  [{index}] {rel}: file not found")
            continue
        text = planned.get(rel, path.read_text())
        if item["marker"] in text:
            skipped.append(f"{rel} [{index}]: already applied")
            continue
        anchor = item["anchor"]
        found = text.count(anchor)
        expect_all = item.get("count") == "all"
        if found == 0 or (found != 1 and not expect_all):
            problems.append(
                f"  [{index}] {rel}: expected "
                f"{'>=1' if expect_all else 'exactly 1'} match, found {found}\n"
                f"        anchor starts: {anchor.splitlines()[0][:76]!r}"
            )
            continue
        planned[rel] = text.replace(anchor, item["replacement"], -1 if expect_all else 1)

    if problems:
        print("ABORTED - NOTHING was written. Every problem, so one round-trip fixes all:")
        print()
        for problem in problems:
            print(problem)
        for echo in echoes:
            print()
            print(echo)
        return 1

    for rel, content in sorted(planned.items()):
        Path(rel).parent.mkdir(parents=True, exist_ok=True)
        Path(rel).write_text(content)
        print(f"wrote {rel}")
    for note in skipped:
        print(f"skip  {note}")
    if not planned:
        print("nothing to do - already applied")

    print()
    print("Rebuild the frontend and run its test suite.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
