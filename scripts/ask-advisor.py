"""Ask Advisor: a slide-over that opens with what moved since you last looked.

A dashboard already shows the numbers. What it cannot do is notice that you have been
away four days and that revenue moved while you were - which is the whole difference
between a briefing and one more panel of figures, and why this has to remember when each
person last read one.

The owner's three choices, implemented as chosen:
  * a slide-over on EVERY page, so the briefing is computed against the filters already
    on screen rather than the whole portfolio;
  * an `advisor_last_seen` table (one row per user, one timestamp) so "since you last
    looked" is real rather than a fixed window with a friendly label;
  * Revenue and Profit lead.

Decisions inside it that are easy to get wrong, and wrong silently:

  * The panel renders WITHOUT the chat assistant being configured. The briefing needs no
    API key. Gating it behind one would leave the panel blank in exactly the state this
    deployment is in today.
  * Read is marked on CLOSE, not on fetch and not on open. Fetching marks nothing, so a
    background tab cannot eat the news; closing is what says "I read it", so re-opening
    within a session still shows the same briefing.
  * A role that cannot see revenue is TOLD so, in a note. "Revenue: $0" and "Revenue: not
    included in your role" look identical to a careless implementation and nothing alike
    to a reader.
  * The window never runs past the filter's own end date, and never past today. date_to
    can legitimately sit in the future on a month-to-date filter; briefing someone on days
    that have not happened would invent a collapse.
  * A second visit the same day shows the usual week rather than an empty window dressed
    up as news.
  * No percentage off a zero base - "+100%" from nothing is a division artefact.

THE MIGRATION IS WRITTEN HERE, NOT SHIPPED PRE-BAKED. Its down_revision is set to
whatever head this repository is actually on when the script runs, because a revision
invented against a stale tree is how you get two alembic heads and a failed deploy. If it
finds more than one head, it refuses rather than guessing.

The head is found by PARSING the migration files, not by matching them. The first version
of this used a regex that only recognised `down_revision: str | None = "x"`, so any file
written as plain `down_revision = "x"` - or as a merge revision's tuple of parents - had
its parent go unrecorded, and that parent then looked like a head. It reported three heads
on a tree that has one, and refused a deploy over it. Python's own parser knows every
spelling of an assignment; a regex knows the one you thought of.

A guard in the existing suite caught something worth keeping: test_models_metadata pins
the exact set of mapped tables, so a new table cannot appear without someone deciding it
should. `advisor_last_seen` is added to that list deliberately, alongside its migration.

Verified: ruff, mypy --strict, 12 new backend tests, 8 new frontend tests, the migration
applied over asyncpg by the existing migration test, tsc, eslint.

ALL-OR-NOTHING: everything is checked before anything is written; any failure reports every
problem, prints the offending files, and writes nothing. Idempotent.
"""

