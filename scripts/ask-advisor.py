MAX_ECHO_LINES = 400
VERSIONS = Path("backend/alembic/versions")


def _assignments(path: Path) -> dict[str, object]:
    """Module-level `revision` / `down_revision` values, parsed rather than matched.

    A regex was tried first and got this wrong in production: it only recognised the
    annotated form `down_revision: str | None = "x"`, so any file written as plain
    `down_revision = "x"` - or as a merge revision's tuple - had its parent go
    unrecorded, and that parent then looked like a head. It reported three heads on a
    tree that has one. Python's own parser knows every spelling; nothing else does.
    """
    found: dict[str, object] = {}
    try:
        tree = ast.parse(path.read_text())
    except SyntaxError:
        return found
    for node in tree.body:
        targets: list[ast.expr] = []
        if isinstance(node, ast.Assign):
            targets = list(node.targets)
            value = node.value
        elif isinstance(node, ast.AnnAssign) and node.value is not None:
            targets = [node.target]
            value = node.value
        else:
            continue
        for target in targets:
            if isinstance(target, ast.Name) and target.id in ("revision", "down_revision"):
                try:
                    found[target.id] = ast.literal_eval(value)
                except (ValueError, SyntaxError):
                    pass
    return found


def alembic_head() -> tuple[str | None, str]:
    """The single revision nothing else points at, or why there isn't one."""
    revisions: dict[str, str] = {}
    parents: set[str] = set()
    for path in sorted(VERSIONS.glob("*.py")):
        values = _assignments(path)
        rev = values.get("revision")
        if isinstance(rev, str):
            revisions[rev] = path.name
        down = values.get("down_revision")
        # A merge revision names several parents. Each one is a parent, not a head.
        if isinstance(down, str):
            parents.add(down)
        elif isinstance(down, (tuple, list)):
            parents.update(d for d in down if isinstance(d, str))
    heads = sorted(set(revisions) - parents)
    if len(heads) == 1:
        return heads[0], revisions[heads[0]]
    if not heads:
        return None, "no head found - the migration graph looks circular"
    # Print what each supposed head actually declares. If this is a real branch the
    # lines below show it; if it is a parsing problem they show that too, in one trip.
    lines = [f"{len(heads)} heads:"]
    for head in heads:
        name = revisions[head]
        declared = _assignments(VERSIONS / name).get("down_revision")
        lines.append(f"      {head}  {name}  down_revision={declared!r}")
    lines.append("      Confirm with `alembic heads` before merging - this needs a human.")
    return None, "\n".join(lines)


def main() -> int:
    if not Path("backend/app").is_dir() or not Path("frontend/app").is_dir():
        print("ABORTED: run this from the repository root")
        return 1

    data = json.loads(base64.b64decode(PAYLOAD.strip()).decode())
    problems: list[str] = []
    echo_paths: list[str] = []
    planned: dict[str, str] = {}
    skipped: list[str] = []

    migration = data["migration"]
    marker = 'revision: str = "' + migration["revision"] + '"'
    if any(marker in p.read_text() for p in VERSIONS.glob("*.py")):
        skipped.append(migration["path"] + ": revision already present")
    else:
        head, detail = alembic_head()
        if head is None:
            problems.append("  alembic: " + detail + ". Nothing written - this needs a human.")
        else:
            content = re.sub(
                r'^down_revision: str \| None = "[^"]+"',
                'down_revision: str | None = "' + head + '"',
                migration["content"],
                count=1,
                flags=re.M,
            )
            content = re.sub(r"^Revises: .*$", "Revises: " + head, content, count=1, flags=re.M)
            planned[migration["path"]] = content
            skipped.append(migration["path"] + ": parented to " + head + " (" + detail + ")")

    for rel, content in data["new_files"].items():
        path = Path(rel)
        if path.exists() and path.read_text() == content:
            skipped.append(rel + ": already present and identical")
            continue
        planned[rel] = content

    for index, item in enumerate(data["edits"], start=1):
        rel = item["path"]
        path = Path(rel)
        if not path.exists():
            problems.append(f"  [{index}] {rel}: file not found")
            continue
        text = planned.get(rel, path.read_text())
        if item["marker"] in text:
            skipped.append(f"{rel} [{index}]: already applied")
            continue
        anchor = item["anchor"]
        found = text.count(anchor)
        if found != 1:
            problems.append(
                f"  [{index}] {rel}: expected exactly 1 match, found {found}\n"
                f"        anchor starts: {anchor.splitlines()[0][:76]!r}"
            )
            if rel not in echo_paths:
                echo_paths.append(rel)
            continue
        planned[rel] = text.replace(anchor, item["replacement"], 1)

    if problems:
        print("ABORTED - NOTHING was written. Every problem, so one round-trip fixes all:")
        print()
        for problem in problems:
            print(problem)
        for rel in echo_paths:
            lines = Path(rel).read_text().splitlines()
            print()
            print(f"───── {rel} ({len(lines)} lines) ─────")
            print("\n".join(lines[:MAX_ECHO_LINES]))
            if len(lines) > MAX_ECHO_LINES:
                print("… truncated …")
        return 1

    for rel, content in sorted(planned.items()):
        Path(rel).parent.mkdir(parents=True, exist_ok=True)
        Path(rel).write_text(content)
        print("wrote " + rel)
    for note in skipped:
        print("note  " + note)
    if not planned:
        print("nothing to do - already applied")

    print()
    print("Rebuild, run `alembic upgrade head`, then the test suites.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
