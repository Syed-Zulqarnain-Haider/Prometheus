MAX_ECHO_LINES = 500


def main() -> int:
    if not Path("frontend/app").is_dir():
        print("ABORTED: run this from the repository root")
        return 1

    data = json.loads(base64.b64decode(PAYLOAD.strip()).decode())
    item = data["replacements"][0]
    path = Path(item["path"])
    if not path.exists():
        print(f"ABORTED: {item['path']} not found")
        return 1

    current = path.read_text()
    if current == item["content"]:
        print(f"{item['path']}: already applied")
        return 0

    actual = hashlib.sha256(current.encode()).hexdigest()
    if actual != item["expect_sha256"]:
        print("ABORTED - NOTHING was written.")
        print()
        print(f"  {item['path']} is not the file this was written against.")
        print(f"    expected sha256 {item['expect_sha256'][:16]}…")
        print(f"    found            {actual[:16]}…")
        print("    Its contents follow so it can be redone without another round-trip.")
        lines = current.splitlines()
        print()
        print(f"───── {item['path']} ({len(lines)} lines) ─────")
        print("\n".join(lines[:MAX_ECHO_LINES]))
        if len(lines) > MAX_ECHO_LINES:
            print("… truncated …")
        return 1

    path.write_text(item["content"])
    print(f"wrote {item['path']}")
    print()
    print("Rebuild the frontend.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
